import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import exifr from 'exifr'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const legalDir = path.join(root, 'public', 'legal')
const outFile = path.join(root, 'src', 'data', 'legal.manifest.ts')

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp'])

const metaByFile = {
  'dti-business-name-registration.png': {
    title: 'DTI business name registration',
    alt: 'DTI Certificate of Business Name Registration — ADAO LOGISTICS SERVICES',
    layout: 'portrait',
  },
  'ppa-tappp-permit.png': {
    title: 'PPA TAPPP permit',
    alt: 'Philippine Ports Authority Transport Accreditation Permit and Pass',
    layout: 'portrait',
  },
  'bir-receipt-invoice-notice.png': {
    title: 'BIR receipt / invoice notice',
    alt: 'Bureau of Internal Revenue notice to issue receipt or invoice',
    layout: 'landscape',
  },
}

function orientationToRotate(orientation) {
  switch (orientation) {
    case 3:
      return 180
    case 6:
      return 90
    case 8:
      return 270
    default:
      return 0
  }
}

async function listImages() {
  let entries = []
  try {
    entries = await readdir(legalDir, { withFileTypes: true })
  } catch {
    return []
  }
  return entries
    .filter((e) => e.isFile() && IMAGE_EXT.has(path.extname(e.name).toLowerCase()))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b))
}

const files = await listImages()
const items = []

for (const file of files) {
  const fullPath = path.join(legalDir, file)
  let rotate = 0
  try {
    const orientation = await exifr.orientation(fullPath)
    rotate = orientationToRotate(orientation)
  } catch {
    rotate = 0
  }
  const meta = metaByFile[file] ?? {
    title: file.replace(/\.[^.]+$/, '').replace(/-/g, ' '),
    alt: 'Compliance document',
    layout: 'portrait',
  }
  items.push({
    src: `/legal/${file}`,
    rotate,
    alt: meta.alt,
    title: meta.title,
    layout: meta.layout,
  })
}

const ts = `/* Auto-generated by scripts/normalize-legal-manifest.mjs */
export type LegalDocument = {
  src: string
  rotate: 0 | 90 | 180 | 270
  alt: string
  title: string
  layout: 'portrait' | 'landscape'
}

export const legalDocuments: LegalDocument[] = ${JSON.stringify(items, null, 2)}
`

await writeFile(outFile, ts, 'utf8')
console.log(`Wrote ${outFile} (${items.length} documents)`)
