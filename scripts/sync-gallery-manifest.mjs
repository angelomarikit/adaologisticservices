import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const galleryRoot = path.join(root, 'public', 'gallery')
const outFile = path.join(root, 'src', 'data', 'gallery.manifest.ts')

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif'])

const categoryMeta = {
  trucking: {
    title: 'Trucking Services',
    description:
      'Road haulage and container movement with equipment suited for port transfers and NLEX corridor deliveries.',
  },
  'sea-freight': {
    title: 'Sea Freight Forwarding',
    description:
      'Coordination for import and export cargo tied to vessel schedules, documentation, and last-mile trucking.',
  },
  'container-safekeeping': {
    title: 'Container Safekeeping',
    description:
      'Secure yard storage and staging so your boxes stay accounted for between trips and customs release.',
  },
  'lift-off-out': {
    title: 'Lift Off / Out',
    description:
      'On-site lifting and positioning — loading, offloading, and crane-assisted handling at the facility.',
  },
  facility: {
    title: 'Our Facility & Area',
    description:
      'Operations along the Marilao NLEX service road — yard access, equipment on standby, and space to work safely.',
  },
}

async function listImages(dir) {
  let entries = []
  try {
    entries = await readdir(dir, { withFileTypes: true })
  } catch {
    return []
  }
  return entries
    .filter((e) => e.isFile() && IMAGE_EXT.has(path.extname(e.name).toLowerCase()))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b))
}

const categories = []
for (const slug of Object.keys(categoryMeta)) {
  const dir = path.join(galleryRoot, slug)
  const files = await listImages(dir)
  categories.push({
    slug,
    ...categoryMeta[slug],
    images: files.map((file) => `/gallery/${slug}/${file}`),
  })
}

const ts = `/* Auto-generated by scripts/sync-gallery-manifest.mjs — do not edit by hand */
export type GalleryCategory = {
  slug: string
  title: string
  description: string
  images: string[]
}

export const galleryCategories: GalleryCategory[] = ${JSON.stringify(categories, null, 2)}
`

await writeFile(outFile, ts, 'utf8')
console.log(`Wrote ${outFile} (${categories.length} categories)`)
