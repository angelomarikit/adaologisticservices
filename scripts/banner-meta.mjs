import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const banner = path.join(root, 'public', 'brand', 'banner.jpg')
const out = path.join(root, 'src', 'data', 'banner.ts')

const { width, height } = await sharp(banner).metadata()
if (!width || !height) throw new Error('Could not read banner dimensions')

const ts = `/** Auto-generated by scripts/banner-meta.mjs */
export const bannerMeta = {
  src: '/brand/banner.jpg',
  width: ${width},
  height: ${height},
  aspectRatio: '${width} / ${height}',
} as const
`

await writeFile(out, ts, 'utf8')
console.log(`Banner ${width}x${height} → ${out}`)
